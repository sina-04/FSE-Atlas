export const catalogue: Entity[] = [];
function add(
  kind: Kind,
  id: string,
  title: Localized,
  summary: Localized,
  tags: string[],
  sections: Entity['sections'] = [],
  extra: Partial<Entity> = {},
) {
  const item: Entity = {
    id,
    slug: id,
    kind,
    title,
    summary,
    category: tags[0] || kind,
    tags,
    status: 'published',
    sources: [editorial],
    sections,
    ...extra,
  };
  catalogue.push(item);
  return item;
}
